# BDA400 Assignment 2: Display and visualize imported stock data
# Run from the Assignment2 directory; internet required for Yahoo Finance data.
source("01_load_and_statistics.R")
stock_data <- load_stock_data("portfolio.txt")
statistics <- calculate_all_statistics(stock_data)
print(statistics, row.names = FALSE)

# Each symbol is stored in a separate data frame within the named stock_data list.
for (symbol in names(stock_data)) {
  cat("\n---", symbol, "stock data (first 6 rows) ---\n")
  print(head(stock_data[[symbol]]))
  cat("\n---", symbol, "stock data (last 6 rows) ---\n")
  print(tail(stock_data[[symbol]]))
}

# Reproducible PNG visualizations generated by base R.
for (symbol in names(stock_data)) {
  df <- stock_data[[symbol]]
  sma20 <- TTR::SMA(df$Close, n = 20)
  png(filename = paste0(symbol, "_close_and_sma20.png"), width = 1100, height = 650, res = 120)
  plot(df$Date, df$Close, type = "l", col = "steelblue", lwd = 2,
       xlab = "Date", ylab = "Price (USD)", main = paste(symbol, "Closing Price and 20-Day Moving Average"))
  lines(df$Date, sma20, col = "firebrick", lwd = 2)
  legend("topleft", legend = c("Daily close", "20-day SMA"),
         col = c("steelblue", "firebrick"), lty = 1, lwd = 2, bty = "n")
  grid()
  dev.off()
}
write.csv(statistics, "stock_statistics.csv", row.names = FALSE)
cat("\nSaved summary statistics and one chart per successfully downloaded symbol.\n")
